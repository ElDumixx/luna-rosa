// Builds Luna Rosa as a PWA (an installable web app) into dist/, ready for GitHub Pages.
//   npm run build:pwa                       → served from the root of a domain (or <user>.github.io)
//   EXPO_BASE_URL=/luna-rosa npm run build:pwa → served from https://<user>.github.io/luna-rosa/
// On top of `expo export -p web` it adds what makes it feel like an app on the iPhone and Android home screen:
// the manifest, home-screen icon and full-screen tags, an offline cache (service worker), a 404 page that opens the
// app on any address (GitHub Pages has no server-side routing) and .nojekyll (so GitHub serves the _expo folder).
const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const dist = path.join(root, "dist");
// "/luna-rosa/" style, or "/" at the root
const base = ("/" + (process.env.EXPO_BASE_URL || "").replace(/^\/+|\/+$/g, "") + "/").replace(/\/+/g, "/");
const version = new Date().toISOString().replace(/\D/g, "").slice(0, 12);

console.log(`Exportando la web (base ${base})…`);
fs.rmSync(dist, { recursive: true, force: true });
execSync("npx expo export -p web --output-dir dist", { cwd: root, stdio: "inherit", env: { ...process.env, EXPO_BASE_URL: base === "/" ? "" : base.slice(0, -1) } });

// --- manifest: name, colors and icons for "Add to Home Screen" ---
const manifest = {
  name: "Luna Rosa",
  short_name: "Luna Rosa",
  description: "Tu ciclo y tu regla, con Lu. Tus datos se quedan en tu móvil.",
  lang: "es",
  id: base,
  start_url: base,
  scope: base,
  display: "standalone",
  orientation: "any",
  background_color: "#FFF7F9",
  theme_color: "#FFF7F9",
  icons: [
    { src: `${base}icon-192.png`, sizes: "192x192", type: "image/png", purpose: "any" },
    { src: `${base}icon-512.png`, sizes: "512x512", type: "image/png", purpose: "any" },
    { src: `${base}icon-512.png`, sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
};
fs.writeFileSync(path.join(dist, "manifest.webmanifest"), JSON.stringify(manifest, null, 2));

// --- service worker: the app opens without connection once it was opened once ---
// Pages are fetched fresh when there is connection (so updates arrive), files with a hash in their name are
// cached forever, everything else is served from the cache and refreshed in the background.
fs.writeFileSync(path.join(dist, "sw.js"), `// Luna Rosa offline cache. Generated by scripts/build-pwa.js.
const CACHE = "luna-rosa-${version}";
const BASE = ${JSON.stringify(base)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll([BASE, BASE + "manifest.webmanifest", BASE + "icon-192.png"])).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== location.origin) return;
  if (req.mode === "navigate") {
    // any address inside the app opens the app's page (offline too)
    e.respondWith(fetch(req).then((r) => { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(BASE, copy)); return r; })
      .catch(() => caches.match(BASE)));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => {
    const net = fetch(req).then((r) => { if (r.ok) { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); } return r; });
    return hit && /-[0-9a-f]{16,}\\./.test(url.pathname) ? hit : hit ? (net.catch(() => hit), hit) : net;
  }));
});
`);

// --- the page: home-screen tags, theme colors, safe areas and the service worker ---
const head = `
    <meta name="description" content="${manifest.description}" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-title" content="Luna Rosa" />
    <meta name="apple-mobile-web-app-status-bar-style" content="default" />
    <meta name="theme-color" content="#FFF7F9" media="(prefers-color-scheme: light)" />
    <meta name="theme-color" content="#150D12" media="(prefers-color-scheme: dark)" />
    <link rel="manifest" href="${base}manifest.webmanifest" />
    <link rel="apple-touch-icon" href="${base}apple-touch-icon.png" />
    <link rel="icon" type="image/png" sizes="192x192" href="${base}icon-192.png" />
    <style>html,body{background:#FFF7F9}@media (prefers-color-scheme: dark){html,body{background:#150D12}}</style>
    <script>if ("serviceWorker" in navigator) addEventListener("load", () => navigator.serviceWorker.register("${base}sw.js", { scope: "${base}" }).catch(() => {}));</script>
`;
const indexPath = path.join(dist, "index.html");
let html = fs.readFileSync(indexPath, "utf8")
  .replace('<html lang="en">', '<html lang="es">')
  .replace(/<meta name="viewport"[^>]*>/, '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, shrink-to-fit=no" />')
  .replace(/<link rel="icon"[^>]*>/g, "")
  .replace("</head>", `${head}  </head>`);
fs.writeFileSync(indexPath, html);
fs.writeFileSync(path.join(dist, "404.html"), html); // GitHub Pages: /day/… and other addresses open the app
fs.writeFileSync(path.join(dist, ".nojekyll"), ""); // otherwise GitHub hides the _expo folder

console.log(`\nListo: dist/ (PWA, base ${base}).`);
